import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { stories } from '../src/data/stories.js';

const target = resolve(import.meta.dirname, '../src/data/finalStories.js');
const source = `// Generated from the reviewed story library. Do not edit this file directly.\n\nexport const stories = ${JSON.stringify(stories, null, 2)};\n\nexport function fillStory(template, answers) {\n  return template.replace(/\\{([^}]+)\\}(色?)/g, (_, key, colorSuffix) => {\n    const answer = answers[key] ?? \`\${'{'}\${key}}\`;\n    if (key === '颜色' && colorSuffix === '色' && answer.endsWith('色')) return answer;\n    return \`\${answer}\${colorSuffix}\`;\n  });\n}\n`;

await writeFile(target, source, 'utf8');
console.log(`Generated ${stories.length} reviewed stories.`);
