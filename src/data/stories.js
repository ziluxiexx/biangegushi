export function fillStory(template, answers) {
  return template.replace(/\{([^}]+)\}(色?)/g, (_, key, colorSuffix) => {
    const answer = answers[key] ?? `{${key}}`;
    if (key === '颜色' && colorSuffix === '色' && answer.endsWith('色')) return answer;
    return `${answer}${colorSuffix}`;
  });
}
